-- =====================================================================
-- Greenfield Community Library Management System
-- Portfolio 1: Relational Schema (PostgreSQL)
-- =====================================================================
-- Run this whole script in the library_db database.
-- It drops existing tables first, so it can be re-run safely.
-- Tables are created parents-first, because a foreign key can only
-- point to a table that already exists.
-- =====================================================================

DROP TABLE IF EXISTS fine        CASCADE;
DROP TABLE IF EXISTS loan        CASCADE;
DROP TABLE IF EXISTS staff       CASCADE;
DROP TABLE IF EXISTS member      CASCADE;
DROP TABLE IF EXISTS book_copy   CASCADE;
DROP TABLE IF EXISTS book_author CASCADE;
DROP TABLE IF EXISTS author      CASCADE;
DROP TABLE IF EXISTS book        CASCADE;
DROP TABLE IF EXISTS branch      CASCADE;

-- ---------------------------------------------------------------------
-- 1. BRANCH: each physical library location
-- ---------------------------------------------------------------------
CREATE TABLE branch (
    branch_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    address     VARCHAR(255) NOT NULL
);

-- ---------------------------------------------------------------------
-- 2. BOOK: one row per title (not per physical copy)
-- ---------------------------------------------------------------------
CREATE TABLE book (
    book_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn              VARCHAR(17)  NOT NULL UNIQUE,
    title             VARCHAR(255) NOT NULL,
    publisher         VARCHAR(150),
    publication_year  INT CHECK (publication_year BETWEEN 1450 AND 2100),
    category          VARCHAR(50)  NOT NULL,
    item_type         VARCHAR(20)  NOT NULL DEFAULT 'Book'
                      CHECK (item_type IN ('Book', 'Journal', 'E-book'))
);

-- ---------------------------------------------------------------------
-- 3. AUTHOR
-- ---------------------------------------------------------------------
CREATE TABLE author (
    author_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(100) NOT NULL,
    last_name   VARCHAR(100) NOT NULL
);

-- ---------------------------------------------------------------------
-- 4. BOOK_AUTHOR: junction table resolving the many-to-many
--    relationship between BOOK and AUTHOR.
--    Composite primary key stops the same author being linked
--    to the same book twice.
-- ---------------------------------------------------------------------
CREATE TABLE book_author (
    book_id     INT NOT NULL REFERENCES book(book_id)     ON DELETE CASCADE,
    author_id   INT NOT NULL REFERENCES author(author_id) ON DELETE CASCADE,
    PRIMARY KEY (book_id, author_id)
);

-- ---------------------------------------------------------------------
-- 5. BOOK_COPY: each physical copy held at a branch.
--    (Named book_copy rather than copy, because COPY is also a
--    PostgreSQL command name.)
-- ---------------------------------------------------------------------
CREATE TABLE book_copy (
    copy_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     INT NOT NULL REFERENCES book(book_id),
    branch_id   INT NOT NULL REFERENCES branch(branch_id),
    status      VARCHAR(20) NOT NULL DEFAULT 'Available'
                CHECK (status IN ('Available', 'On Loan', 'Lost', 'Damaged'))
);

-- ---------------------------------------------------------------------
-- 6. MEMBER: registered library users
-- ---------------------------------------------------------------------
CREATE TABLE member (
    member_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name       VARCHAR(100) NOT NULL,
    last_name        VARCHAR(100) NOT NULL,
    email            VARCHAR(150) NOT NULL UNIQUE,
    phone            VARCHAR(20),
    membership_type  VARCHAR(20)  NOT NULL DEFAULT 'Standard'
                     CHECK (membership_type IN ('Standard', 'Student', 'Premium')),
    join_date        DATE NOT NULL DEFAULT CURRENT_DATE
);

-- ---------------------------------------------------------------------
-- 7. STAFF: employees, each assigned to one branch
-- ---------------------------------------------------------------------
CREATE TABLE staff (
    staff_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(100) NOT NULL,
    last_name   VARCHAR(100) NOT NULL,
    role        VARCHAR(30)  NOT NULL
                CHECK (role IN ('Librarian', 'Branch Manager', 'Administrator')),
    branch_id   INT NOT NULL REFERENCES branch(branch_id)
);

-- ---------------------------------------------------------------------
-- 8. LOAN: a member borrowing one copy, processed by a staff member.
--    return_date is NULL while the book is still out.
-- ---------------------------------------------------------------------
CREATE TABLE loan (
    loan_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    copy_id      INT NOT NULL REFERENCES book_copy(copy_id),
    member_id    INT NOT NULL REFERENCES member(member_id),
    staff_id     INT NOT NULL REFERENCES staff(staff_id),
    borrow_date  DATE NOT NULL DEFAULT CURRENT_DATE,
    due_date     DATE NOT NULL,
    return_date  DATE,
    CHECK (due_date > borrow_date),
    CHECK (return_date IS NULL OR return_date >= borrow_date)
);

-- ---------------------------------------------------------------------
-- 9. FINE: at most one fine per loan (UNIQUE on loan_id makes the
--    relationship one-to-zero-or-one).
-- ---------------------------------------------------------------------
CREATE TABLE fine (
    fine_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id      INT NOT NULL UNIQUE REFERENCES loan(loan_id),
    amount       NUMERIC(8,2) NOT NULL CHECK (amount > 0),
    paid_status  VARCHAR(10)  NOT NULL DEFAULT 'Unpaid'
                 CHECK (paid_status IN ('Unpaid', 'Paid'))
);

-- =====================================================================
-- Verification: list every table and its column count
-- =====================================================================
SELECT table_name,
       COUNT(*) AS column_count
FROM information_schema.columns
WHERE table_schema = 'public'
GROUP BY table_name
ORDER BY table_name;
